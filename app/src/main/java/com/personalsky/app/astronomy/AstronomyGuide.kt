enum class AstronomyTone(val label: String, val subtitle: String) {
    SCIENCE("Строго", "проверенный факт"),
    LIGHT("С улыбкой", "лёгкий взгляд"),
    EPIC("Космический путь", "спокойная эпика")
}

data class AstronomyGuideEntry(
    val title: String,
    val headline: String,
    val paragraphs: List<String>,
    val observationTip: String,
    val sourcesLabel: String
)

object AstronomyGuide {
    fun entryFor(durationDays: Int, tone: AstronomyTone): AstronomyGuideEntry = when (durationDays) {
        5 -> cassiopeia(tone)
        7 -> ursaMajor(tone)
        else -> orion(tone)
    }

